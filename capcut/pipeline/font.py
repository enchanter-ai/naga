GLYPH_W = 5
GLYPH_H = 7
_FALLBACK = _G["?"]


def text_width(text, scale=1, tracking=1):
    """Pixel width of `text` at the given scale, including inter-glyph gaps."""
    if not text:
        return 0
    n = len(text)
    return n * GLYPH_W * scale + (n - 1) * tracking * scale


def draw_text(frame, text, x, y, scale=1, color=(255, 255, 255),
              shadow=(0, 0, 0), tracking=1, alpha=1.0):
    """Blit `text` with its top-left corner at (x, y).

    A one-texel offset shadow is drawn first; it is what keeps light text
    legible over a bright sky.
    """
    if alpha <= 0.0:
        return
    passes = []
    if shadow is not None:
        passes.append((scale, shadow, x + scale, y + scale))
    passes.append((scale, color, x, y))
    for sc, col, ox, oy in passes:
        r, g, b = col
        cx = ox
        for ch in text:
            rows = _G.get(ch) or _G.get(ch.upper()) or _FALLBACK
            for gy in range(GLYPH_H):
                row = rows[gy]
                py = oy + gy * sc
                for gx in range(GLYPH_W):
                    if row[gx] != "#":
                        continue
                    px = cx + gx * sc
                    for dy in range(sc):
                        yy = py + dy
                        if yy < 0 or yy >= frame.h:
                            continue
                        for dx in range(sc):
                            xx = px + dx
                            if 0 <= xx < frame.w:
                                frame.blend_px(xx, yy, r, g, b, alpha)
            cx += (GLYPH_W + tracking) * sc
